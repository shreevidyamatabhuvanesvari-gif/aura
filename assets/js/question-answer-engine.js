/**
 * AURA Question Answer Engine
 * Version: 1.0.0
 * Status: Question Answer Foundation
 */

window.QuestionAnswerEngine = {

    VERSION: "1.0.0",

    normalize(text) {

        return String(text || "")
            .trim()
            .toLowerCase();
    },

    answer(question) {

        const q =
            this.normalize(
                question
            );

        /*
        |--------------------------------------------------------------------------
        | Krishna
        |--------------------------------------------------------------------------
        */

        if (

            q.includes(
                "कृष्ण कौन"
            )

        ) {

            return {

                success: true,

                type:
                    "question",

                topic:
                    "krishna",

                content:

                    "श्रीकृष्ण भारतीय दर्शन और महाभारत परंपरा के प्रमुख पात्र हैं, जिन्हें ज्ञान, कर्म और भक्ति के आदर्श के रूप में देखा जाता है।"
            };
        }

        /*
        |--------------------------------------------------------------------------
        | India
        |--------------------------------------------------------------------------
        */

        if (

            q.includes(
                "भारत क्या है"
            ) ||

            q.includes(
                "भारत कौन"
            )

        ) {

            return {

                success: true,

                type:
                    "question",

                topic:
                    "india",

                content:

                    "भारत एक प्राचीन सभ्यता और आधुनिक लोकतांत्रिक राष्ट्र है, जिसकी सांस्कृतिक और आध्यात्मिक विरासत अत्यंत समृद्ध है।"
            };
        }

        /*
        |--------------------------------------------------------------------------
        | Soul
        |--------------------------------------------------------------------------
        */

        if (

            q.includes(
                "आत्मा क्या है"
            )

        ) {

            return {

                success: true,

                type:
                    "question",

                topic:
                    "atma",

                content:

                    "आत्मा को अनेक दार्शनिक परंपराओं में चेतना और अस्तित्व के मूल स्वरूप के रूप में माना गया है।"
            };
        }

        /*
        |--------------------------------------------------------------------------
        | Knowledge
        |--------------------------------------------------------------------------
        */

        if (

            q.includes(
                "ज्ञान क्या है"
            )

        ) {

            return {

                success: true,

                type:
                    "question",

                topic:
                    "knowledge",

                content:

                    "ज्ञान अनुभव, अध्ययन और समझ के माध्यम से प्राप्त होने वाली बौद्धिक संपदा है।"
            };
        }

        /*
        |--------------------------------------------------------------------------
        | Default
        |--------------------------------------------------------------------------
        */

        return {

            success: true,

            type:
                "question",

            topic:
                "general",

            content:

                "यह प्रश्न महत्वपूर्ण है। इसके उत्तर के लिए ज्ञान, तर्क और संदर्भ का संतुलित अध्ययन आवश्यक है।"
        };
    }
};
